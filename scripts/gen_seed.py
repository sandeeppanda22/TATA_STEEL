"""Generate db/01_seed.sql directly from the source Excel (Source/*.xlsx).
Incremental: imports build_data.build_dataset(), which parses the workbooks
in memory, and emits plain INSERT ... ON CONFLICT DO NOTHING statements -
no ORM, no JSON intermediate on disk. Re-run any time the source Excel
changes; a road/activity already in the DB is left untouched (its edits and
weekly actuals survive), only genuinely new rows get inserted.

BR-09 special case: if a road's own sheet has no "RCC Drain" activity but
Phase-Summary gives a drain_m target, this script adds ONE synthetic
activity row for it (unit='RMT', planned_qty=drain_m, from_summary_only=TRUE)
so drain progress can be tracked via the same weekly_entry mechanism. This
is the one explicit, user-approved exception to BR-02 ("nothing invented").

Run: python3 scripts/gen_seed.py
"""
import datetime
import os

import build_data
import config

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "db", "01_seed.sql")


def sql_str(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def sql_num(v):
    return "NULL" if v is None else str(v)


def sql_date(v):
    if not v:
        return "NULL"
    return f"DATE '{v}'"


def sql_bool(v):
    return "TRUE" if v else "FALSE"


def build():
    data = build_data.build_dataset()

    lines = [
        "-- Generated by scripts/gen_seed.py directly from Source/*.xlsx",
        f"-- Generated at: {datetime.datetime.now().isoformat()}",
        f"-- Source files: {', '.join(data.get('source_files', []))}",
        "SET search_path TO tata_road;",
        "",
    ]

    road_rows, activity_rows, issue_rows = [], [], []

    for road in data["roads"]:
        rn = road["road_no"]
        road_rows.append(
            f"({rn}, {road.get('phase', 1)}, {sql_str(road.get('scheme_sl_no'))}, "
            f"{sql_str(road['location'])}, {sql_str(road.get('line_manager'))}, "
            f"{sql_str(road.get('vendor'))}, {sql_str(road.get('road_type'))}, "
            f"{sql_num(road.get('length_m', 0))}, {sql_num(road.get('width_m'))}, "
            f"{sql_num(road.get('drain_m', 0))}, {sql_num(road.get('cost_cr'))}, "
            f"{sql_date(road.get('start_date'))}, {sql_date(road.get('end_date'))}, "
            f"{sql_str(road.get('source_file'))})"
        )

        row_order = 0
        has_drain_activity = False
        for a in road["activities"]:
            row_order += 1
            seq_no = None
            if a["activity"] in config.ACTIVITY_SEQUENCE:
                seq_no = config.ACTIVITY_SEQUENCE.index(a["activity"]) + 1
            major = a["activity"] if a["activity"] in config.MAJOR_ORDER else None
            is_drain = a["activity"] == "RCC Drain"
            if is_drain:
                has_drain_activity = True
            activity_rows.append(
                f"({rn}, {sql_num(seq_no)}, {row_order}, {sql_str(a['raw_name'])}, "
                f"{sql_str(major)}, {sql_num(a.get('weight', 0))}, {sql_str(a.get('unit'))}, "
                f"{sql_num(a.get('planned_qty', 0) or 0)}, {sql_date(a.get('start_date'))}, "
                f"{sql_date(a.get('end_date'))}, {sql_bool(is_drain)}, FALSE)"
            )

        # BR-09: synthesize the drain row from Phase-Summary if the sheet has none.
        if not has_drain_activity and road.get("drain_m", 0) > 0:
            row_order += 1
            seq_no = config.ACTIVITY_SEQUENCE.index("RCC Drain") + 1
            activity_rows.append(
                f"({rn}, {seq_no}, {row_order}, 'RCC Drain', NULL, 0, 'RMT', "
                f"{sql_num(road['drain_m'])}, {sql_date(road.get('start_date'))}, "
                f"{sql_date(road.get('end_date'))}, TRUE, TRUE)"
            )

    for i in data["data_issues"]:
        issue_rows.append(
            f"({sql_str(i.get('road_no')) if str(i.get('road_no')).isdigit() else 'NULL'}, "
            f"{sql_str(i.get('activity'))}, {sql_str(i.get('field'))}, "
            f"{sql_str(i.get('value'))}, {sql_str(i.get('issue'))})"
        )

    # Incremental: a road/activity already in the DB (e.g. from a previous
    # run, or a prior source workbook) is left exactly as-is - ON CONFLICT DO
    # NOTHING, not DO UPDATE, so any edits made via the dashboard UI (or any
    # weekly actuals already entered on it) are never overwritten by a
    # re-run. Only genuinely new road_no / (road_no, raw_name) rows insert.
    lines.append("INSERT INTO road (road_no, phase, scheme_sl_no, location, line_manager,")
    lines.append("    vendor, road_type, length_m, width_m, drain_planned_m, cost_cr,")
    lines.append("    start_date, end_date, source_file) VALUES")
    lines.append(",\n".join(road_rows) + "\nON CONFLICT (road_no) DO NOTHING;")
    lines.append("")

    lines.append("INSERT INTO activity (road_no, seq_no, sheet_row_order, raw_name, major,")
    lines.append("    weight_pct, unit, planned_qty, start_date, end_date, is_drain,")
    lines.append("    from_summary_only) VALUES")
    lines.append(",\n".join(activity_rows) + "\nON CONFLICT (road_no, raw_name) DO NOTHING;")
    lines.append("")

    if issue_rows:
        lines.append("INSERT INTO data_issue (road_no, activity_name, field, value, issue) VALUES")
        lines.append(",\n".join(issue_rows) +
                      "\nON CONFLICT (COALESCE(road_no, -1), COALESCE(activity_name, ''), "
                      "COALESCE(field, ''), COALESCE(value, ''), issue) DO NOTHING;")
        lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {OUT}: {len(road_rows)} roads, {len(activity_rows)} activities, "
          f"{len(issue_rows)} issues")


if __name__ == "__main__":
    build()
